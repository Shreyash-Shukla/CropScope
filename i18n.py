def t(key: str, lang: str = "en") -> str:
    """Retrieve localized string for key in target language, with English fallback."""
    if key not in TRANSLATIONS:
        return key
    lang_map = TRANSLATIONS[key]
    return lang_map.get(lang, lang_map.get("en", key))


def get_quick_prompts(lang: str = "en") -> List[str]:
    """Retrieve localized quick question prompts for the given language."""
    return QUICK_PROMPTS.get(lang, QUICK_PROMPTS["en"])


def get_language_names() -> List[str]:
    """List all supported language labels for Streamlit selection widgets."""
    return [meta["label"] for meta in SUPPORTED_LANGUAGES.values()]


def get_code_from_label(label: str) -> str:
    """Map UI label back to language code (e.g. 'हिन्दी (Hindi)' -> 'hi')."""
    for code, meta in SUPPORTED_LANGUAGES.items():
        if meta["label"] == label or meta["native"] == label:
            return code
    return "en"


def format_crop_label(crop: str, lang: str = "en") -> str:
    """Format crop name in the user's selected language, keeping value intact."""
    crop_key = f"crop_{crop}"
    if crop_key in TRANSLATIONS:
        return t(crop_key, lang)
    return crop


def format_stage_label(stage: str, lang: str = "en") -> str:
    """Format growth stage name in the user's selected language, keeping value intact."""
    stage_key = f"stage_{stage}"
    if stage_key in TRANSLATIONS:
        return t(stage_key, lang)
    return stage


